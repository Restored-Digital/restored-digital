import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const p = JSON.parse(readFileSync(join(root, "data/pricing.json"), "utf8"));

const usd = (n) => "$" + n.toLocaleString("en-US");
const days = (n) => `${n} business day${n === 1 ? "" : "s"}`;
const firstYear = (t) => t.commitPrice + p.care.monthly * p.care.commitMonths;
const careLine = `${usd(p.care.monthly)}/month for ${p.care.commitMonths} months`;

// Guard: stored discounts must equal price minus commit price.
for (const t of p.tiers) {
  if (t.price - t.commitPrice !== t.discount) {
    throw new Error(`${t.name}: discount ${t.discount} does not equal ${t.price} - ${t.commitPrice}`);
  }
}

const headCells = p.tiers.map((t) => `<th scope="col">${t.name}</th>`).join("");
const row = (label, fn) =>
  `<tr><th scope="row">${label}</th>${p.tiers.map((t) => `<td>${fn(t)}</td>`).join("")}</tr>`;

